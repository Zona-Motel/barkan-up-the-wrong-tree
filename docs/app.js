/* Renders the diff corpus. Data comes from
   data/diffs.js (generated by build.py). The page is read-only. */

(function () {
  "use strict";

  var DATA = window.BARKAN_DATA || { articles: [], summary: {} };
  var NOTES = window.BARKAN_NOTES || {};

  // ---------- rendering helpers ----------

  function el(tag, cls, txt) {
    var e = document.createElement(tag);
    if (cls) e.className = cls;
    if (txt !== undefined) e.textContent = txt;
    return e;
  }
  function esc(s) {
    return String(s).replace(/[&<>]/g, function (c) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;" }[c];
    });
  }
  // Split one inline diff into the two sides it describes: the original with its
  // deletions marked, the updated with its insertions marked. Also returns the
  // plain text of each side, used to match the diff back to its paragraph.
  var MARK = /\[-([\s\S]*?)-\]|\{\+([\s\S]*?)\+\}/g;
  function splitInline(inline) {
    var oldHtml = "", newHtml = "", oldText = "", newText = "", last = 0, m;
    MARK.lastIndex = 0;
    while ((m = MARK.exec(inline)) !== null) {
      var between = inline.slice(last, m.index);
      oldHtml += esc(between); newHtml += esc(between);
      oldText += between; newText += between;
      if (m[1] !== undefined) {
        oldHtml += "<del>" + esc(m[1]) + "</del>";
        oldText += m[1];
      } else {
        newHtml += "<ins>" + esc(m[2]) + "</ins>";
        newText += m[2];
      }
      last = m.index + m[0].length;
    }
    var tail = inline.slice(last);
    oldHtml += esc(tail); newHtml += esc(tail);
    oldText += tail; newText += tail;
    return { oldHtml: oldHtml, newHtml: newHtml, oldText: oldText, newText: newText };
  }

  // Destinations present on each side, so a link the correction really did add or
  // drop is marked where it sits rather than only in the list at the end. Keyed on
  // the URL alone: the same destination hung on different words is the sentence
  // changing, not the link, and marking it gone-and-new would say otherwise.
  function linkSets(change) {
    var side = function (blocks) {
      var set = {};
      blocks.forEach(function (b) {
        (b.links || []).forEach(function (l) { set[l.url] = true; });
      });
      return set;
    };
    var o = side(change.old), n = side(change.new);
    return {
      old: function (l) { return n[l.url] ? "" : "gone"; },
      new: function (l) { return o[l.url] ? "" : "new"; }
    };
  }

  // paragraph text -> marked-up HTML for that side of the change
  function highlightMap(change) {
    var map = { old: {}, new: {} };
    (change.paired || []).forEach(function (p) {
      var x = splitInline(p.inline);
      map.old[x.oldText] = x.oldHtml;
      map.new[x.newText] = x.newHtml;
    });
    return map;
  }
  var CARD_MODE = false;   // set by the ?card= screenshot view
  var KIND = { REPLACE: "rewritten", INSERT: "added", DELETE: "deleted" };

  var LINK_KIND = {
    removed: "Removed",
    added: "Added",
    // The URL is untouched; the words carrying it are not. Named rather than
    // counted, because nothing about the link itself changed.
    reworded: "Same link, new wording"
  };

  function quoted(list) {
    return list.map(function (t) { return "“" + t + "”"; }).join(", ");
  }

  // URLs are never shortened. What distinguishes two links is usually at the end
  // — a query string like ?ref=compactmag.com, or a slug tail — so eliding it would
  // hide the evidence the page exists to show. Long URLs wrap instead.
  function shortUrl(u) { return u; }

  // navigator.clipboard needs a secure context, which file:// is not -- and the
  // page is meant to work when opened by double-clicking it. Fall back to the
  // old selection-and-execCommand route there.
  function copyText(text) {
    if (navigator.clipboard && window.isSecureContext) {
      return navigator.clipboard.writeText(text);
    }
    return new Promise(function (resolve, reject) {
      var ta = document.createElement("textarea");
      ta.value = text;
      ta.setAttribute("readonly", "");
      ta.style.position = "fixed";
      ta.style.top = "-1000px";
      document.body.appendChild(ta);
      ta.select();
      var ok = false;
      try { ok = document.execCommand("copy"); } catch (e) { ok = false; }
      document.body.removeChild(ta);
      ok ? resolve() : reject();
    });
  }

  // The anchor has to keep its "a" prefix: openFor feeds the hash straight to
  // querySelector, and #046 is not a valid selector.
  function permalink(id) {
    return location.origin === "null" || location.protocol === "file:"
      ? location.href.split("#")[0] + "#a" + id
      : location.origin + location.pathname + location.search + "#a" + id;
  }

  function ymd(ts) {
    ts = String(ts || "");
    return ts.length >= 8 ? ts.slice(0, 4) + "-" + ts.slice(4, 6) + "-" + ts.slice(6, 8) : "";
  }

  // Turn each anchor phrase in the passage into the link it actually carried.
  // Works on text nodes so it cannot break the <del>/<ins> markup already there,
  // and skips text already inside an <a> so a repeated phrase takes the next one.
  function linkify(root, links) {
    (links || []).forEach(function (l) {
      if (!l.anchor) return;
      var walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, null);
      var n;
      while ((n = walker.nextNode())) {
        if (n.parentNode.nodeName === "A") continue;
        var i = n.nodeValue.indexOf(l.anchor);
        if (i === -1) continue;
        var hit = n.splitText(i);
        hit.splitText(l.anchor.length);
        var a = document.createElement("a");
        a.href = l.url;
        a.target = "_blank";
        a.rel = "noopener";
        a.textContent = hit.nodeValue;
        hit.parentNode.replaceChild(a, hit);
        return;   // one link per entry; the rest are found on later passes
      }
    });
  }

  function renderBlock(b, marked, linkState) {
    var d = el("div", "blk");
    var p = el("p", "txt" + (b.tag === "blockquote" ? " q" : ""));
    if (marked) p.innerHTML += marked; else p.appendChild(document.createTextNode(b.text));
    linkify(p, b.links);
    d.appendChild(p);
    if (b.links && b.links.length) {
      var ul = el("ul", "links");
      b.links.forEach(function (l) {
        var li = document.createElement("li");
        if (linkState) li.className = linkState(l);
        li.appendChild(el("span", "anchor", "‘" + l.anchor + "’"));
        li.appendChild(document.createTextNode(" → "));
        var a = el("a", null, shortUrl(l.url));
        a.href = l.url; a.target = "_blank"; a.rel = "noopener";
        li.appendChild(a);
        ul.appendChild(li);
      });
      d.appendChild(ul);
    }
    return d;
  }

  function renderSide(blocks, label, marks, linkState) {
    var td = el("td");
    td.setAttribute("data-label", label);
    if (!blocks.length) { td.appendChild(el("p", "empty", "(this passage did not exist before)")); return td; }
    blocks.forEach(function (b) {
      td.appendChild(renderBlock(b, marks ? marks[b.text] : null, linkState));
    });
    return td;
  }

  // ---------- article section ----------

  function renderArticle(a) {
    var sec = el("article", "piece");
    sec.id = "a" + a.id;
    sec.dataset.id = a.id;

    // Collapsed by default: 67 sections is too much to scroll past. Opens on a
    // deep link, on a search hit, or on click.
    var det = document.createElement("details");
    var sum = document.createElement("summary");

    sum.appendChild(el("span", "c-id", a.id));

    var t = el("span", "c-title");
    t.appendChild(el("span", "title-text", a.title));
    sum.appendChild(t);

    sum.appendChild(el("span", "c-date", ymd(a.archiveTimestamp) || "—"));


    sum.appendChild(el("span", "c-pass", String(a.changes.length)));
    // Only links that came or went. A URL reattached to different words is not
    // a link change, so it is left out of this count.
    var rem = 0, add = 0;
    a.linkChanges.forEach(function (x) {
      if (x.kind === "removed") rem++;
      else if (x.kind === "added") add++;
    });
    var lbl = [rem ? "−" + rem : "", add ? "+" + add : ""].filter(Boolean).join(" ");
    sum.appendChild(el("span", "c-links", lbl || "—"));

    // Copies a link to this article. It lives inside the <summary>, so its click
    // has to be kept from reaching the toggle.
    var perma = el("button", "perma");
    perma.type = "button";
    // "Copy link" alone would be ambiguous: the row also carries links to the
    // article itself and to two snapshots of it. Name what is being copied.
    perma.setAttribute("aria-label", "Copy link to this diff: " + a.title);
    var ico = el("span", "ico", "📋");
    var tip = el("span", "tip", "Copy link to this diff");
    perma.appendChild(ico);
    perma.appendChild(tip);
    perma.addEventListener("click", function (e) {
      e.preventDefault();
      e.stopPropagation();
      copyText(permalink(a.id)).then(function () {
        ico.textContent = "✓";
        tip.textContent = "Copied";
      }, function () {
        ico.textContent = "✕";
        tip.textContent = "Press ⌘C to copy";
      });
      perma.classList.add("done");
      setTimeout(function () {
        ico.textContent = "📋";
        tip.textContent = "Copy link to this diff";
        perma.classList.remove("done");
      }, 1400);
    });
    sum.appendChild(perma);

    det.appendChild(sum);
    sec.appendChild(det);

    // Live page, the snapshot the diff was built from, and the newest snapshot —
    // so the article is still reachable if nymag takes it down.
    var meta = el("div", "meta");
    [["Live page", a.liveUrl, ""],
     ["Original snapshot", a.archiveUrl, a.archiveTimestamp],
     ["Latest snapshot", a.latestUrl, a.latestTimestamp]]
      .forEach(function (p) {
        if (!p[1] || p[1] === "NONE") return;
        var label = p[0] + (p[2] ? " " + ymd(p[2]) : "");
        var x = el("a", null, label);
        x.href = p[1]; x.target = "_blank"; x.rel = "noopener";
        meta.appendChild(x);
      });
    det.appendChild(meta);

    var table = el("table", "changes");
    var cg = document.createElement("colgroup");
    ["c-n", "c-old", "c-new"].forEach(function (c) {
      var col = document.createElement("col"); col.className = c; cg.appendChild(col);
    });
    table.appendChild(cg);
    var thead = document.createElement("thead");
    thead.innerHTML = "<tr><th></th><th>Original</th><th>Updated</th></tr>";
    table.appendChild(thead);
    var tb = document.createElement("tbody");

    a.changes.forEach(function (c) {
      var tr = document.createElement("tr");
      tr.id = "a" + a.id + "-c" + c.n;

      var n = el("td", "n");
      n.setAttribute("data-label", "Change");
      var link = el("a", null, "#" + c.n);
      link.href = "#a" + a.id + "-c" + c.n;
      n.appendChild(link);
      n.appendChild(el("span", "kind", KIND[c.type] || c.type.toLowerCase()));
      tr.appendChild(n);

      var marks = highlightMap(c), ls = linkSets(c);
      tr.appendChild(renderSide(c.old, "Original", marks.old, ls.old));
      tr.appendChild(renderSide(c.new, "Updated", marks.new, ls.new));

      // Searchable haystack. Blocks are joined by a character no query can
      // contain, so a quoted phrase cannot match across two paragraphs.
      tr.dataset.text = c.old.concat(c.new)
        .map(function (b) { return fold(b.text); }).join("\u0000");
      tb.appendChild(tr);
    });
    table.appendChild(tb);
    det.appendChild(table);

    if (a.linkChanges.length) {
      var d = el("div", "delta");
      d.appendChild(el("h3", null, "Link changes"));
      var ul = document.createElement("ul");
      a.linkChanges.forEach(function (x) {
        var li = document.createElement("li");
        li.className = x.kind;
        li.appendChild(el("span", "tag", LINK_KIND[x.kind]));
        li.appendChild(el("span", "anchor", " " + (
          x.kind === "reworded" ? quoted(x.old) + " → " + quoted(x.new)
                                : "on the words " + quoted(x.old.concat(x.new))
        ) + " — "));
        var lk = el("a", null, shortUrl(x.url));
        lk.href = x.url; lk.target = "_blank"; lk.rel = "noopener";
        li.appendChild(lk);
        ul.appendChild(li);
      });
      d.appendChild(ul);
      det.appendChild(d);
    }

    // Hand-written commentary from data/notes.js. Most articles have none, and
    // those show no heading -- an empty "Note" would read as an omission.
    var note = NOTES[a.id];
    if (note) {
      var nd = el("div", "note");
      nd.appendChild(el("h3", null, "Note"));
      var np = document.createElement("p");
      np.innerHTML = note;   // the file is hand-authored, so its markup is trusted
      nd.appendChild(np);
      det.appendChild(nd);
    }
    return sec;
  }

  // ---------- index ----------

  function watchToggles() {
    document.querySelectorAll("article.piece details").forEach(function (d) {
      d.addEventListener("toggle", function () {
        if (d.open) d.dataset.pinned = "1"; else delete d.dataset.pinned;
      });
    });
  }

  function openFor(hash) {
    if (!hash) return;
    var t = document.querySelector(hash);
    if (!t) return;
    // #a019 points at the <article>, whose <details> is a child; #a019-c1 points
    // at a row inside that <details>. Look down first, then up.
    var d = t.querySelector ? t.querySelector("details") : null;
    if (!d && t.closest) d = t.closest("details");
    if (d) { d.open = true; d.dataset.pinned = "1"; }
    t.scrollIntoView();
  }

  function setAll(open) {
    document.querySelectorAll("article.piece details").forEach(function (d) {
      d.open = open;
      if (open) d.dataset.pinned = "1"; else delete d.dataset.pinned;
    });
  }

  // ---------- filters ----------

  // These articles are full of curly apostrophes and quotes, so a phrase copied
  // out of one and typed back with straight ones would never match. Both the
  // text and the query are folded to straight punctuation and single spaces
  // before they are compared.
  function fold(s) {
    return String(s).toLowerCase()
      .replace(/[\u2018\u2019\u02bc]/g, "'")
      .replace(/[\u201c\u201d]/g, '"')
      .replace(/[\u2013\u2014]/g, "-")
      .replace(/\s+/g, " ")
      .trim();
  }

  // "a phrase in quotes" is one term that must appear intact; anything else is
  // split on spaces into separate terms, all of which must appear, in any order.
  // A quote left open while still typing runs to the end of the query, so the
  // results narrow with each keystroke instead of waiting for the closing one.
  function parseQuery(q) {
    var out = [], re = /"([^"]*)"?|(\S+)/g, m;
    while ((m = re.exec(q)) !== null) {
      var t = (m[1] !== undefined ? m[1] : m[2]).trim();
      if (t) out.push(t);
    }
    return out;
  }


  function applyFilters() {
    var terms = parseQuery(fold(document.getElementById("f-text").value));
    var q = terms.length > 0;
    var shownA = 0, shownC = 0;

    DATA.articles.forEach(function (a) {
      var sec = document.getElementById("a" + a.id);
      if (!sec) return;
      var rowsVisible = 0;
      sec.querySelectorAll("tbody tr").forEach(function (tr) {
        var hay = tr.dataset.text;
        var hide = q && !terms.every(function (t) { return hay.indexOf(t) !== -1; });
        tr.classList.toggle("hidden", hide);
        if (!hide) rowsVisible++;
      });
      var show = rowsVisible > 0;
      sec.classList.toggle("hidden", !show);
      var det = sec.querySelector("details");
      if (det && !det.dataset.pinned) det.open = q && show;
      if (show) { shownA++; shownC += rowsVisible; }
    });
    document.getElementById("count").textContent =
      shownA + " of 67 articles, " + shownC + " passages";
  }

  // ---------- screenshot card ----------

  function renderCard(target) {
    var m = /^a?(\d{3})-c(\d+)$/.exec(target);
    if (!m) return false;
    var a = DATA.articles.filter(function (x) { return x.id === m[1]; })[0];
    if (!a) return false;
    var c = a.changes.filter(function (x) { return String(x.n) === m[2]; })[0];
    if (!c) return false;

    CARD_MODE = true;
    document.body.className = "card-mode";
    var wrap = document.querySelector(".wrap");
    wrap.textContent = "";
    var card = el("div", "card");
    card.appendChild(el("h1", null, a.title));
    var ts = a.archiveTimestamp || "";
    card.appendChild(el("div", "card-meta",
      "Change " + c.n + " of " + a.changes.length + " · passage " + (KIND[c.type] || "") +
      (ts.length >= 8 ? " · original captured " + ts.slice(0, 4) + "-" + ts.slice(4, 6) + "-" + ts.slice(6, 8) : "")));

    var cm = highlightMap(c), cl = linkSets(c);
    [["Original", c.old, cm.old, cl.old], ["Updated", c.new, cm.new, cl.new]]
      .forEach(function (p) {
        var pane = el("div", "pane");
        pane.appendChild(el("h2", null, p[0]));
        if (!p[1].length) pane.appendChild(el("p", "empty", "(this passage did not exist before)"));
        p[1].forEach(function (b) { pane.appendChild(renderBlock(b, p[2][b.text], p[3])); });
        card.appendChild(pane);
      });

    var f = document.createElement("footer");
    f.textContent = a.liveUrl;
    card.appendChild(f);
    wrap.appendChild(card);
    document.title = a.title + " — change " + c.n + " — The 67 Columns";
    return true;
  }

  // ---------- boot ----------

  var card = new URLSearchParams(location.search).get("card");
  if (card && renderCard(card)) return;

  var main = document.getElementById("articles");
  var frag = document.createDocumentFragment();
  DATA.articles.forEach(function (a) { frag.appendChild(renderArticle(a)); });
  main.appendChild(frag);

  // The search runs on Enter, not on every keystroke: filtering as you type
  // collapses and reopens 67 articles under the cursor, and a quoted phrase is
  // half-typed -- and matches nothing -- for most of the time you are writing it.
  var box = document.getElementById("f-text");
  box.addEventListener("keydown", function (e) {
    if (e.key === "Enter") { e.preventDefault(); applyFilters(); }
  });
  // Emptying the box restores the full list without asking for Enter, which
  // covers backspacing it out and the clear button inside the field.
  box.addEventListener("input", function () {
    if (box.value === "") applyFilters();
  });
  box.addEventListener("search", applyFilters);

  watchToggles();
  document.getElementById("expand-all").addEventListener("click", function () {
    setAll(true);
  });
  // Collapsing also clears the pins, so a later search is free to open its hits again.
  document.getElementById("collapse-all").addEventListener("click", function () {
    setAll(false);
  });

  applyFilters();
  openFor(location.hash);
  window.addEventListener("hashchange", function () { openFor(location.hash); });
})();
